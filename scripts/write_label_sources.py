"""Write reports/label_sources.md: the CPC prefixes and OpenAlex topics behind each domain label.

Topic names are looked up from OpenAlex (single-record lookups are free), so the report records
exactly what each topic ID in config.yaml means.
"""
from __future__ import annotations

import sys
from pathlib import Path

import requests

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.config import get_key, load_config, path  # noqa: E402


def topic_info(base: str, topic_id: str, key: str | None) -> tuple[str, str]:
    """Return (topic name, subfield name) for an OpenAlex topic ID such as T10320."""
    params = {"api_key": key} if key else {}
    r = requests.get(f"{base}/topics/{topic_id}", params=params, timeout=60)
    r.raise_for_status()
    t = r.json()
    return t["display_name"], t["subfield"]["display_name"]


def main() -> None:
    """Build the markdown table for every domain and save it under reports/."""
    cfg = load_config()
    key = get_key("OPENALEX_API_KEY")
    lines = [
        "# Domain label sources",
        "",
        "Generated by `scripts/write_label_sources.py` from config.yaml.",
        "",
        "Patents: primary CPC code, else first matching inventive CPC code, else a Y02E tag "
        "(Renewable Energy). Papers: OpenAlex primary topic.",
        "",
    ]
    for domain, spec in cfg["domains"].items():
        lines += [f"## {domain}", "", "CPC prefixes: " + ", ".join(f"`{p}`" for p in spec["cpc_prefixes"]), ""]
        lines += ["| OpenAlex topic | Name | Subfield |", "|---|---|---|"]
        for tid in spec["openalex_topics"]:
            name, subfield = topic_info(cfg["apis"]["openalex_url"], tid, key)
            lines.append(f"| {tid} | {name} | {subfield} |")
        lines.append("")
    out = path("reports") / "label_sources.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
